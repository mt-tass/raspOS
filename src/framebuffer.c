int fb_init(uint32_t width, uint32_t height, uint32_t depth) {
    volatile uint32_t __attribute__((aligned(16))) mbox[36];
    
    mbox[0] = 35 * 4;
    mbox[1] = 0;
    mbox[2] = TAG_SET_PHYS_WH;
    mbox[3] = 8;
    mbox[4] = 8;                
    mbox[5] = width;            // Value(width) 
    mbox[6] = height;           // Value(height) 
    mbox[7] = TAG_SET_VIRT_WH;
    mbox[8] = 8;
    mbox[9] = 8;
    mbox[10] = width;
    mbox[11] = height;
    mbox[12] = 0x00048009;      // SET_VIRTUAL_OFFSET
    mbox[13] = 8;
    mbox[14] = 8;
    mbox[15] = 0;               // X offset 
    mbox[16] = 0;               // Y offset 
    mbox[17] = TAG_SET_BITS_PER_PX;
    mbox[18] = 4;
    mbox[19] = 4;
    mbox[20] = depth;           
    mbox[21] = TAG_SET_PIXEL_ORDER;      
    mbox[22] = 4;
    mbox[23] = 4;
    mbox[24] = 1;               // 1 = RGB 
    mbox[25] = TAG_ALLOCATE_BUFFER;
    mbox[26] = 8;
    mbox[27] = 8;
    mbox[28] = 4096;    
    mbox[29] = 0;               
    mbox[30] = TAG_GET_PITCH;
    mbox[31] = 4;
    mbox[32] = 4;
    mbox[33] = 0;  
    mbox[34] = 0;
    if (mailbox_call(PROP, mbox) == 0 && mbox[20] == depth && mbox[28] != 0) {
        fb_buffer = (uint8_t*)((uintptr_t)mbox[28] & 0x3FFFFFFF); 
        fb_width = mbox[5];
        fb_height = mbox[6];
        fb_pitch = mbox[33];
        fb_depth = mbox[20];
        return 0;
    }
    return -1;
}
static inline uint32_t get_pixel_val(color c) {
    return (c.alpha << 24) | (c.blue << 16) | (c.green << 8) | c.red;
}
void fb_draw_pixel(uint32_t x, uint32_t y, color c) {
    if (x >= fb_width || y >= fb_height){
        return;
    }
    uint32_t offs = (y * fb_pitch) + (x * 4);
    *((volatile uint32_t*)(fb_buffer + offs)) = get_pixel_val(c);
}

void fb_draw_rectangle(uint32_t x1, uint32_t y1, uint32_t w, uint32_t h, color c) {
    uint32_t x2 = x1 + w;
    uint32_t y2 = y1 + h;
    for (uint32_t y = y1; y < y2 && y < fb_height; y++) {
        for (uint32_t x = x1; x < x2 && x < fb_width; x++) {
            fb_draw_pixel(x,y,c);
        }
    }
}
void fb_draw_char(uint32_t x, uint32_t y, char ch, color fg, color bg) {
    if (ch < 32 || ch > 127){
        ch = '?';
    }
    const uint8_t *ctemp = font_8x8[ch - 32]; 
    for (int i = 0; i < 8; i++) {
        for (int j = 0; j <8; j++) {
            uint8_t mask = 1<<j;
            color col = (ctemp[i] & mask) ? fg : bg;
            fb_draw_pixel(x+j,y+i,col);
        }
    }
}
void fb_draw_string(uint32_t x, uint32_t y, const char *str, color fg, color bg) {
    uint32_t cur_x = x;
    uint32_t cur_y = y;
    while(*str){
        if (*str == '\r'){
            cur_x = x;
        }
        else if(*str == '\n') {
            cur_x = x; 
            cur_y += 8;
        }
        else{
            fb_draw_char(cur_x, cur_y, *str, fg, bg);
            cur_x += 8;
        }
        str++;
    }
}
void fb_fill_screen(color c) {
    uint32_t val = get_pixel_val(c);
    uint32_t *ptr = (uint32_t*)fb_buffer;
    uint32_t size = (fb_pitch / 4) * fb_height;
    for (uint32_t i = 0; i < size; i++) {
        ptr[i] = val;
    }
}